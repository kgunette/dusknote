// Turn the Source Serif 4 TTFs into a pdfmake virtual file system (base64), so the report
// PDF renders in Source Serif fully offline (no network font fetch). Regenerate after
// swapping a font file: `node scripts/make-font-vfs.mjs`.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const fontsDir = join(here, '..', 'src', 'report', 'fonts');

// normal, bold, italics — bolditalics is intentionally omitted (never used, saves ~190KB).
const files = ['SourceSerif4-Regular.ttf', 'SourceSerif4-Semibold.ttf', 'SourceSerif4-It.ttf'];

const entries = files
  .map((f) => `  '${f}': '${readFileSync(join(fontsDir, f)).toString('base64')}',`)
  .join('\n');

const out =
  `// GENERATED by scripts/make-font-vfs.mjs — do not edit by hand.\n` +
  `// Source Serif 4 (Adobe, SIL Open Font License 1.1) as a pdfmake virtual file system.\n` +
  `/* eslint-disable */\n` +
  `export const sourceSerifVfs: Record<string, string> = {\n${entries}\n};\n`;

writeFileSync(join(fontsDir, 'vfs.ts'), out);
console.log('wrote src/report/fonts/vfs.ts');
